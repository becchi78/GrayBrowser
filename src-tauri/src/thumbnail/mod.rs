//! Stateless thumbnail generation queue: no persisted job table.
//! "Resume after restart" falls out for free from re-enumerating `videos`
//! rows still missing any of their 6
//! `thumbnails/<folder-subdir>/[id]_<slot>.webp` files every time this runs.

pub mod paths;
pub(crate) mod publish;
pub mod reassign;
pub mod worker;

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, MutexGuard};
use std::thread;
use std::time::Instant;

use gb_core::ports::ffmpeg::FfmpegAdapter;
use gb_core::thumbnail_progress::{FinishOutcome, ProgressSnapshot, ThumbnailProgress};

use crate::db::queries::{read_watch_folders, WatchFoldersReadError};
use crate::db::Db;
use crate::events::CatalogNotifier;
use crate::reachability::ReachabilityRegistry;

const WORKER_THREAD_COUNT: usize = 4;

#[derive(Clone)]
pub struct ThumbnailQueueHandle {
    /// Video ids currently being generated, shared by every clone. Queues
    /// started independently (startup, post-scan, .wb import) and the manual
    /// retry command all consult it, so one video is never generated by two
    /// of them at once.
    in_flight: Arc<Mutex<HashSet<String>>>,
    /// Pending-video bookkeeping shared by every queue, so a video listed by
    /// several queues is counted once in the progress denominator.
    progress: Arc<Mutex<ThumbnailProgress>>,
    notify_gate: Arc<Mutex<()>>,
}

impl Default for ThumbnailQueueHandle {
    fn default() -> Self {
        Self {
            in_flight: Arc::new(Mutex::new(HashSet::new())),
            progress: Arc::new(Mutex::new(ThumbnailProgress::new())),
            notify_gate: Arc::new(Mutex::new(())),
        }
    }
}

/// Releases a video's in-flight claim on drop, so the claim is given back on
/// success, on `Err`, and on panic alike.
pub struct ClaimGuard {
    in_flight: Arc<Mutex<HashSet<String>>>,
    video_id: String,
}

impl Drop for ClaimGuard {
    fn drop(&mut self) {
        lock_ignoring_poison(&self.in_flight).remove(&self.video_id);
    }
}

/// A panic while holding this lock cannot leave the set logically
/// inconsistent (single insert/remove), and a poisoned lock must not keep a
/// video claimed forever or panic inside `Drop`.
fn lock_ignoring_poison(set: &Mutex<HashSet<String>>) -> MutexGuard<'_, HashSet<String>> {
    set.lock().unwrap_or_else(|e| e.into_inner())
}

impl ThumbnailQueueHandle {
    pub fn progress_snapshot(&self) -> ProgressSnapshot {
        self.progress_lock().snapshot()
    }

    /// Poisoning is ignored for the same reason as `lock_ignoring_poison`:
    /// each update is a single self-contained call.
    fn progress_lock(&self) -> MutexGuard<'_, ThumbnailProgress> {
        self.progress.lock().unwrap_or_else(|e| e.into_inner())
    }

    fn track_pending<'a>(&self, ids: impl IntoIterator<Item = &'a str>) {
        self.progress_lock().add(ids);
    }

    fn finish_tracked(&self, id: &str, outcome: FinishOutcome) {
        self.progress_lock().finish(id, outcome);
    }

    /// Emits the current progress. The snapshot is taken inside
    /// `notify_gate`, so concurrent workers cannot deliver an older snapshot
    /// after a newer one (which would leave the UI showing a stale count
    /// after the final reset). `progress` itself is not held while emitting.
    fn publish_progress<N: CatalogNotifier>(&self, notifier: &N) {
        let _gate = self.notify_gate.lock().unwrap_or_else(|e| e.into_inner());
        let s = self.progress_snapshot();
        notifier.notify_thumbnail_progress(s.done, s.total);
    }

    /// Claims `video_id` for generation. `None` means another worker is
    /// already generating it; the caller should skip it and let that worker
    /// finish.
    pub fn try_claim(&self, video_id: &str) -> Option<ClaimGuard> {
        if lock_ignoring_poison(&self.in_flight).insert(video_id.to_string()) {
            Some(ClaimGuard {
                in_flight: Arc::clone(&self.in_flight),
                video_id: video_id.to_string(),
            })
        } else {
            None
        }
    }
}

/// Deletes leftover `*.tmp` files directly under `thumbnails_root` and one
/// directory level below it, returning how many were removed. A crash or a
/// failed rename can strand them (`{id}_{i}.webp.tmp`, the per-run
/// `{id}_{i}.webp.{pid}-{n}.tmp`, `{id}.wb_legacy.webp.tmp`); nothing ever
/// reads them again. Only names ending in `.tmp` are touched, so finished
/// `.webp` files are never at risk. Must run before any generation starts,
/// since an in-progress file would look the same. Failures are logged only:
/// thumbnails are regenerable.
pub fn remove_orphan_tmp_files(thumbnails_root: &Path) -> usize {
    remove_tmp_files_in(thumbnails_root, true)
}

fn remove_tmp_files_in(dir: &Path, descend: bool) -> usize {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => {
            log::warn!(
                "failed to scan {} for orphan .tmp files: {e}",
                dir.display()
            );
            return 0;
        }
    };
    let mut removed = 0;
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            if descend {
                removed += remove_tmp_files_in(&path, false);
            }
        } else if file_type.is_file() && entry.file_name().to_string_lossy().ends_with(".tmp") {
            match std::fs::remove_file(&path) {
                Ok(()) => removed += 1,
                Err(e) => log::warn!("failed to remove orphan tmp file {}: {e}", path.display()),
            }
        }
    }
    removed
}

/// Re-enumerates videos missing a thumbnail and spawns a small fixed worker
/// pool to generate them. Fire-and-forget: runs on a background thread and
/// never blocks the caller (`.setup()` at startup, or `start_scan` after a
/// scan completes -- so a scan never freezes the UI).
///
/// `thumbnails_dir` is the `thumbnails/` root (per-registered-folder
/// subdirectories live under it, see `thumbnail::paths::video_thumbnail_dir`)
/// -- `watch_folders` is fetched once here, up front, and reused both for
/// `list_videos_missing_thumbnails`'s per-row existence check and for
/// resolving each dispatched video's own subdirectory before calling
/// `generate_thumbnail_for_video`, rather than re-querying it per video.
///
/// `notifier` is threaded in only here, not into `worker.rs` -- `worker.rs`'s
/// `generate_thumbnail_for_video`/`list_videos_missing_thumbnails` keep their
/// existing pure/testable signatures unchanged, and the
/// `notify_changed` call sits in this module's per-video step
/// (`generate_claimed`) instead, right after each individual
/// `generate_thumbnail_for_video` call succeeds -- one notification per
/// completed thumbnail, not one at the very end, so the grid fills in
/// incrementally (matching the "list first, thumbnails backfill"
/// experience) rather than freezing until the whole batch is done.
///
/// Videos under a watch folder that is unreachable right now are skipped
/// without spending a retry (opening them would block for ~20s each and
/// permanently fail the video after a few restarts). The skipped videos are
/// picked up again by the follow-up run that fires when the folder returns.
pub fn enqueue_missing_thumbnails<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
    reachability: ReachabilityRegistry,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    thread::spawn(move || {
        run_thumbnail_queue(db, thumbnails_dir, queue, ffmpeg, notifier, reachability)
    });
}

/// The body of `enqueue_missing_thumbnails`, split out so tests can run it
/// synchronously (and several at once) without a detached thread.
fn run_thumbnail_queue<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
    reachability: ReachabilityRegistry,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    if !crate::queue_support::ffmpeg_and_ffprobe_available(ffmpeg.as_ref()) {
        log::warn!(
            "ffmpeg/ffprobe not found on PATH -- skipping thumbnail generation for this run"
        );
        return;
    }

    let watch_folders = match read_watch_folders(&db.read_pool) {
        Ok(folders) => folders,
        Err(WatchFoldersReadError::Query(e)) => {
            log::error!("failed to read watch_folders before enqueueing thumbnails: {e}");
            return;
        }
        Err(WatchFoldersReadError::Connection(e)) => {
            log::error!(
                "failed to acquire a DB connection to read watch_folders before enqueueing \
                     thumbnails: {e}"
            );
            return;
        }
    };

    let pending = match worker::list_videos_missing_thumbnails(&db, &thumbnails_dir, &watch_folders)
    {
        Ok(pending) => pending,
        Err(e) => {
            log::error!("failed to list videos missing thumbnails: {e}");
            return;
        }
    };
    process_pending(
        db,
        thumbnails_dir,
        watch_folders,
        queue,
        ffmpeg,
        notifier,
        pending,
        reachability,
    );
}

/// Generates the given videos on a small worker pool. `pending` is a
/// snapshot that may already be stale (another queue can finish a video
/// after it was listed), so each worker re-checks the files after claiming.
// The handles are bundled into `WorkerContext` for the workers, but this
// entry point keeps taking them one by one so its many direct callers in the
// tests stay unchanged.
#[allow(clippy::too_many_arguments)]
fn process_pending<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    watch_folders: Vec<String>,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
    pending: Vec<(String, PathBuf)>,
    reachability: ReachabilityRegistry,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    if pending.is_empty() {
        return;
    }
    queue.track_pending(pending.iter().map(|(id, _)| id.as_str()));
    queue.publish_progress(notifier.as_ref());

    let worker_count = WORKER_THREAD_COUNT.min(pending.len());
    let pending = Arc::new(Mutex::new(pending.into_iter()));
    let ctx = WorkerContext {
        db,
        thumbnails_dir,
        watch_folders,
        queue,
        ffmpeg,
        notifier,
        reachability,
    };

    crate::queue_support::run_workers_to_completion(worker_count, || {
        let pending = Arc::clone(&pending);
        let ctx = ctx.clone();
        move || worker_loop(&ctx, &pending)
    });
}

/// The handles one worker thread needs, so each worker takes a single clone
/// instead of one per handle.
struct WorkerContext<F, N> {
    db: Db,
    thumbnails_dir: PathBuf,
    watch_folders: Vec<String>,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
    reachability: ReachabilityRegistry,
}

// Written by hand because `#[derive(Clone)]` would demand `F: Clone` and
// `N: Clone`, although only the `Arc`s around them are cloned.
impl<F, N> Clone for WorkerContext<F, N> {
    fn clone(&self) -> Self {
        Self {
            db: self.db.clone(),
            thumbnails_dir: self.thumbnails_dir.clone(),
            watch_folders: self.watch_folders.clone(),
            queue: self.queue.clone(),
            ffmpeg: Arc::clone(&self.ffmpeg),
            notifier: Arc::clone(&self.notifier),
            reachability: self.reachability.clone(),
        }
    }
}

/// One worker thread: takes videos from the shared iterator until it runs
/// dry.
fn worker_loop<F, N>(
    ctx: &WorkerContext<F, N>,
    pending: &Mutex<std::vec::IntoIter<(String, PathBuf)>>,
) where
    F: FfmpegAdapter,
    N: CatalogNotifier,
{
    loop {
        let next = pending.lock().unwrap().next();
        let Some((id, path)) = next else { break };
        process_one(ctx, &id, &path);
    }
}

/// Handles one video from claim to recorded progress. The outcome is
/// recorded here, while the claim is still held, so a video is never seen
/// as unclaimed before its progress is final.
fn process_one<F, N>(ctx: &WorkerContext<F, N>, id: &str, path: &Path)
where
    F: FfmpegAdapter,
    N: CatalogNotifier,
{
    // Held until the end of this function, i.e. past the generate call and
    // the notification.
    let Some(_claim) = ctx.queue.try_claim(id) else {
        log::debug!("thumbnail worker: {id} is already being generated, skipping");
        // The holder may be untracked (e.g. a manual retry) or
        // may have finished already, so nobody else is
        // guaranteed to retire this id.
        ctx.queue.finish_tracked(id, FinishOutcome::SkippedBusy);
        ctx.queue.publish_progress(ctx.notifier.as_ref());
        return;
    };
    let outcome = generate_claimed(ctx, id, path);
    ctx.queue.finish_tracked(id, outcome);
    ctx.queue.publish_progress(ctx.notifier.as_ref());
}

/// Everything done for a claimed video, ending in the outcome to record.
/// Recording is left to the caller so it happens in one place, before the
/// claim is released.
fn generate_claimed<F, N>(ctx: &WorkerContext<F, N>, id: &str, path: &Path) -> FinishOutcome
where
    F: FfmpegAdapter,
    N: CatalogNotifier,
{
    let video_dir = paths::video_thumbnail_dir(
        &ctx.thumbnails_dir,
        &ctx.watch_folders,
        &path.to_string_lossy(),
    );
    // The claim only serializes runs; it can be won right
    // after another queue finished this very video.
    if (0..worker::THUMBNAILS_PER_VIDEO).all(|i| paths::slot_path(&video_dir, id, i).exists()) {
        log::debug!("thumbnail worker: {id} is already complete, skipping");
        if let Err(e) = crate::db::queries::mark_thumbnail_ready(&ctx.db.writer.lock().unwrap(), id)
        {
            log::warn!("failed to backfill thumbnail_ready for {id}: {e}");
        }
        return FinishOutcome::AlreadyGenerated;
    }
    // After the already-complete check, which needs no access
    // to the video. The first question about a folder may
    // block for as long as the share takes to time out; that
    // happens here on the worker, and every later video of
    // the same folder gets the cached answer.
    let path_str = path.to_string_lossy();
    if ctx
        .reachability
        .is_path_unreachable(&path_str, &ctx.watch_folders)
    {
        log::info!("thumbnail worker: skipping {id}, its folder is unreachable right now");
        return FinishOutcome::SkippedUnreachable;
    }
    let started = Instant::now();
    let result =
        worker::generate_thumbnail_for_video(ctx.ffmpeg.as_ref(), &ctx.db, &video_dir, id, path);
    crate::scan::last_report::THUMBNAIL_WORK.record(started.elapsed(), result.is_ok());
    match result {
        Ok(()) => {
            ctx.notifier.notify_changed();
            FinishOutcome::Generated
        }
        Err(e)
            if ctx
                .reachability
                .confirm_path_unreachable(&path_str, &ctx.watch_folders) =>
        {
            // The share went away during the attempt, so the
            // failure says nothing about the video: give the
            // retry back (the worker already counted it).
            log::warn!("thumbnail worker: {id} failed because its folder became unreachable: {e}");
            if let Err(refund_err) =
                crate::db::queries::refund_thumbnail_attempt(&ctx.db.writer.lock().unwrap(), id)
            {
                log::warn!("failed to refund the thumbnail attempt for {id}: {refund_err}");
            }
            FinishOutcome::SkippedUnreachable
        }
        Err(e) => {
            log::warn!("thumbnail worker: giving up on video {id}: {e}");
            // The row can only switch to its failed state if
            // the list is re-read after the attempt count
            // changed. That re-read does not start generation.
            ctx.notifier.notify_changed();
            FinishOutcome::Failed
        }
    }
}

