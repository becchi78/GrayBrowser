pub mod paths;
pub mod reassign;
pub mod worker;

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::thread;
use std::time::Duration;

use gb_core::ports::ffmpeg::FfmpegAdapter;
