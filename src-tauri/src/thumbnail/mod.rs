//! Stateless thumbnail generation queue: no persisted job table.
//! "Resume after restart" falls out for free from re-enumerating `videos`
//! rows still missing any of their 6
//! `thumbnails/<folder-subdir>/[id]_<slot>.webp` files every time this runs.

pub mod migration;
pub mod paths;
pub mod worker;

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::thread;
use std::time::Duration;

use gb_core::ports::ffmpeg::FfmpegAdapter;

use crate::db::Db;
use crate::events::CatalogNotifier;

const WORKER_THREAD_COUNT: usize = 4;
const PAUSE_POLL_INTERVAL: Duration = Duration::from_millis(200);

#[derive(Clone)]
pub struct ThumbnailQueueHandle {
    paused: Arc<AtomicBool>,
    /// Video ids currently being generated, shared by every clone. Queues
    /// started independently (startup, post-scan, .wb import) and the manual
    /// retry command all consult it, so one video is never generated by two
    /// of them at once.
    in_flight: Arc<Mutex<HashSet<String>>>,
}

impl Default for ThumbnailQueueHandle {
    fn default() -> Self {
        Self {
            paused: Arc::new(AtomicBool::new(false)),
            in_flight: Arc::new(Mutex::new(HashSet::new())),
        }
    }
}

/// Releases a video's in-flight claim on drop, so the claim is given back on
/// success, on `Err`, and on panic alike.
pub struct ClaimGuard {
    in_flight: Arc<Mutex<HashSet<String>>>,
    video_id: String,
}

impl Drop for ClaimGuard {
    fn drop(&mut self) {
        lock_ignoring_poison(&self.in_flight).remove(&self.video_id);
    }
}

/// A panic while holding this lock cannot leave the set logically
/// inconsistent (single insert/remove), and a poisoned lock must not keep a
/// video claimed forever or panic inside `Drop`.
fn lock_ignoring_poison(set: &Mutex<HashSet<String>>) -> MutexGuard<'_, HashSet<String>> {
    set.lock().unwrap_or_else(|e| e.into_inner())
}

impl ThumbnailQueueHandle {
    pub fn set_paused(&self, paused: bool) {
        self.paused.store(paused, Ordering::SeqCst);
    }

    pub fn is_paused(&self) -> bool {
        self.paused.load(Ordering::SeqCst)
    }

    /// Claims `video_id` for generation. `None` means another worker is
    /// already generating it; the caller should skip it and let that worker
    /// finish.
    pub fn try_claim(&self, video_id: &str) -> Option<ClaimGuard> {
        if lock_ignoring_poison(&self.in_flight).insert(video_id.to_string()) {
            Some(ClaimGuard {
                in_flight: Arc::clone(&self.in_flight),
                video_id: video_id.to_string(),
            })
        } else {
            None
        }
    }
}

/// Deletes leftover `*.tmp` files directly under `thumbnails_root` and one
/// directory level below it, returning how many were removed. A crash or a
/// failed rename can strand them (`{id}_{i}.webp.tmp`, the per-run
/// `{id}_{i}.webp.{pid}-{n}.tmp`, `{id}.wb_legacy.webp.tmp`); nothing ever
/// reads them again. Only names ending in `.tmp` are touched, so finished
/// `.webp` files are never at risk. Must run before any generation starts,
/// since an in-progress file would look the same. Failures are logged only:
/// thumbnails are regenerable.
pub fn remove_orphan_tmp_files(thumbnails_root: &Path) -> usize {
    remove_tmp_files_in(thumbnails_root, true)
}

fn remove_tmp_files_in(dir: &Path, descend: bool) -> usize {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => {
            log::warn!(
                "failed to scan {} for orphan .tmp files: {e}",
                dir.display()
            );
            return 0;
        }
    };
    let mut removed = 0;
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            if descend {
                removed += remove_tmp_files_in(&path, false);
            }
        } else if file_type.is_file() && entry.file_name().to_string_lossy().ends_with(".tmp") {
            match std::fs::remove_file(&path) {
                Ok(()) => removed += 1,
                Err(e) => log::warn!("failed to remove orphan tmp file {}: {e}", path.display()),
            }
        }
    }
    removed
}

/// Re-enumerates videos missing a thumbnail and spawns a small fixed worker
/// pool to generate them. Fire-and-forget: runs on a background thread and
/// never blocks the caller (`.setup()` at startup, or `start_scan` after a
/// scan completes -- so a scan never freezes the UI).
///
/// `thumbnails_dir` is the `thumbnails/` root (per-registered-folder
/// subdirectories live under it, see `thumbnail::paths::video_thumbnail_dir`)
/// -- `watch_folders` is fetched once here, up front, and reused both for
/// `list_videos_missing_thumbnails`'s per-row existence check and for
/// resolving each dispatched video's own subdirectory before calling
/// `generate_thumbnail_for_video`, rather than re-querying it per video.
///
/// `notifier` is threaded in only here, not into `worker.rs` -- `worker.rs`'s
/// `generate_thumbnail_for_video`/`list_videos_missing_thumbnails` keep their
/// existing pure/testable signatures unchanged, and the
/// `notify_changed` call sits in this orchestration
/// function's own per-worker loop instead, right after each individual
/// `generate_thumbnail_for_video` call succeeds -- one notification per
/// completed thumbnail, not one at the very end, so the grid fills in
/// incrementally (matching the "list first, thumbnails backfill"
/// experience) rather than freezing until the whole batch is done.
pub fn enqueue_missing_thumbnails<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    thread::spawn(move || run_thumbnail_queue(db, thumbnails_dir, queue, ffmpeg, notifier));
}

/// The body of `enqueue_missing_thumbnails`, split out so tests can run it
/// synchronously (and several at once) without a detached thread.
fn run_thumbnail_queue<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    {
        let available = matches!(
            ffmpeg.check_available(),
            Ok(a) if a.ffmpeg_version.is_some() && a.ffprobe_version.is_some()
        );
        if !available {
            log::warn!(
                "ffmpeg/ffprobe not found on PATH -- skipping thumbnail generation for this run"
            );
            return;
        }

        let watch_folders = match db.read_pool.get() {
            Ok(conn) => match crate::db::queries::get_watch_folders(&conn) {
                Ok(folders) => folders,
                Err(e) => {
                    log::error!("failed to read watch_folders before enqueueing thumbnails: {e}");
                    return;
                }
            },
            Err(e) => {
                log::error!(
                    "failed to acquire a DB connection to read watch_folders before enqueueing \
                     thumbnails: {e}"
                );
                return;
            }
        };

        let pending =
            match worker::list_videos_missing_thumbnails(&db, &thumbnails_dir, &watch_folders) {
                Ok(pending) => pending,
                Err(e) => {
                    log::error!("failed to list videos missing thumbnails: {e}");
                    return;
                }
            };
        process_pending(
            db,
            thumbnails_dir,
            watch_folders,
            queue,
            ffmpeg,
            notifier,
            pending,
        );
    }
}

/// Generates the given videos on a small worker pool. `pending` is a
/// snapshot that may already be stale (another queue can finish a video
/// after it was listed), so each worker re-checks the files after claiming.
fn process_pending<F, N>(
    db: Db,
    thumbnails_dir: PathBuf,
    watch_folders: Vec<String>,
    queue: ThumbnailQueueHandle,
    ffmpeg: Arc<F>,
    notifier: Arc<N>,
    pending: Vec<(String, PathBuf)>,
) where
    F: FfmpegAdapter + 'static,
    N: CatalogNotifier + 'static,
{
    if pending.is_empty() {
        return;
    }
    {
        let worker_count = WORKER_THREAD_COUNT.min(pending.len());
        let pending = Arc::new(std::sync::Mutex::new(pending.into_iter()));

        let handles: Vec<_> = (0..worker_count)
            .map(|_| {
                let pending = Arc::clone(&pending);
                let db = db.clone();
                let thumbnails_dir = thumbnails_dir.clone();
                let watch_folders = watch_folders.clone();
                let queue = queue.clone();
                let ffmpeg = Arc::clone(&ffmpeg);
                let notifier = Arc::clone(&notifier);
                thread::spawn(move || loop {
                    while queue.is_paused() {
                        thread::sleep(PAUSE_POLL_INTERVAL);
                    }
                    let next = pending.lock().unwrap().next();
                    let Some((id, path)) = next else { break };
                    // Held until the end of this iteration, i.e. past the
                    // generate call and the notification.
                    let Some(_claim) = queue.try_claim(&id) else {
                        log::debug!("thumbnail worker: {id} is already being generated, skipping");
                        continue;
                    };
                    let video_dir = paths::video_thumbnail_dir(
                        &thumbnails_dir,
                        &watch_folders,
                        &path.to_string_lossy(),
                    );
                    // The claim only serializes runs; it can be won right
                    // after another queue finished this very video.
                    if (0..worker::THUMBNAILS_PER_VIDEO)
                        .all(|i| paths::slot_path(&video_dir, &id, i).exists())
                    {
                        log::debug!("thumbnail worker: {id} is already complete, skipping");
                        if let Err(e) = crate::db::queries::mark_thumbnail_ready(
                            &db.writer.lock().unwrap(),
                            &id,
                        ) {
                            log::warn!("failed to backfill thumbnail_ready for {id}: {e}");
                        }
                        continue;
                    }
                    match worker::generate_thumbnail_for_video(
                        ffmpeg.as_ref(),
                        &db,
                        &video_dir,
                        &id,
                        &path,
                    ) {
                        Ok(()) => notifier.notify_changed(),
                        Err(e) => {
                            log::warn!("thumbnail worker: giving up on video {id}: {e}");
                        }
                    }
                })
            })
            .collect();

        for handle in handles {
            let _ = handle.join();
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::db::test_support::{init_temp_db, insert_test_video};
    use gb_core::ports::ffmpeg::FfmpegAvailability;
    use gb_core::testing::fake_ffmpeg::{FakeCall, FakeFfmpegAdapter};
    use std::sync::atomic::AtomicUsize;

    struct CountingNotifier(AtomicUsize);

    impl CatalogNotifier for CountingNotifier {
        fn notify_changed(&self) {
            self.0.fetch_add(1, Ordering::SeqCst);
        }
    }

    fn available_ffmpeg(extract_delay: Duration) -> Arc<FakeFfmpegAdapter> {
        Arc::new(FakeFfmpegAdapter {
            availability: Ok(FfmpegAvailability {
                ffmpeg_version: Some("7.0".into()),
                ffprobe_version: Some("7.0".into()),
            }),
            duration: Ok(Some(120.0)),
            extract_result: Box::new(move |_seek| {
                thread::sleep(extract_delay);
                Ok(())
            }),
            ..Default::default()
        })
    }

    fn unassigned_dir(root: &Path) -> PathBuf {
        root.join(gb_core::paths::THUMBNAIL_UNASSIGNED_SUBDIR)
    }

    fn thumbnail_ready_flag(db: &Db, id: &str) -> i64 {
        db.writer
            .lock()
            .unwrap()
            .query_row(
                "SELECT thumbnail_ready FROM videos WHERE id = ?1",
                rusqlite::params![id],
                |r| r.get(0),
            )
            .unwrap()
    }

    fn extract_count_for(ffmpeg: &FakeFfmpegAdapter, id: &str) -> usize {
        let prefix = format!("{id}_");
        ffmpeg
            .calls
            .lock()
            .unwrap()
            .iter()
            .filter(|c| match c {
                FakeCall::ExtractThumbnail {
                    output_tmp_path, ..
                } => output_tmp_path
                    .file_name()
                    .is_some_and(|n| n.to_string_lossy().starts_with(&prefix)),
                _ => false,
            })
            .count()
    }

    fn six_finals_exist(dir: &Path, id: &str) -> bool {
        (0..worker::THUMBNAILS_PER_VIDEO).all(|i| dir.join(format!("{id}_{i}.webp")).exists())
    }

    #[test]
    fn two_queues_racing_on_the_same_video_extract_only_once() {
        let (_db_dir, db) = init_temp_db();
        let thumbs = tempfile::tempdir().unwrap();
        insert_test_video(&db, "vid-race", "C:/videos/race.mp4");
        // Slow extraction keeps the first queue's claim held while the
        // second one has already listed the same (still missing) video.
        let ffmpeg = available_ffmpeg(Duration::from_millis(40));
        let notifier = Arc::new(CountingNotifier(AtomicUsize::new(0)));
        let queue = ThumbnailQueueHandle::default();
        let barrier = Arc::new(std::sync::Barrier::new(2));

        let threads: Vec<_> = (0..2)
            .map(|_| {
                let (db, root) = (db.clone(), thumbs.path().to_path_buf());
                let (queue, ffmpeg, notifier) =
                    (queue.clone(), Arc::clone(&ffmpeg), Arc::clone(&notifier));
                let barrier = Arc::clone(&barrier);
                thread::spawn(move || {
                    barrier.wait();
                    run_thumbnail_queue(db, root, queue, ffmpeg, notifier);
                })
            })
            .collect();
        for t in threads {
            t.join().unwrap();
        }

        assert_eq!(
            extract_count_for(&ffmpeg, "vid-race"),
            worker::THUMBNAILS_PER_VIDEO,
            "the video must be extracted by exactly one of the queues"
        );
        assert!(six_finals_exist(&unassigned_dir(thumbs.path()), "vid-race"));
        assert_eq!(thumbnail_ready_flag(&db, "vid-race"), 1);
        assert_eq!(notifier.0.load(Ordering::SeqCst), 1);
    }

    #[test]
    fn an_already_complete_video_in_a_stale_pending_list_is_not_regenerated() {
        let (_db_dir, db) = init_temp_db();
        let thumbs = tempfile::tempdir().unwrap();
        let dir = unassigned_dir(thumbs.path());
        insert_test_video(&db, "vid-done", "C:/videos/done.mp4");
        std::fs::create_dir_all(&dir).unwrap();
        for i in 0..worker::THUMBNAILS_PER_VIDEO {
            std::fs::write(dir.join(format!("vid-done_{i}.webp")), b"original").unwrap();
        }
        let ffmpeg = available_ffmpeg(Duration::ZERO);
        let notifier = Arc::new(CountingNotifier(AtomicUsize::new(0)));

        process_pending(
            db.clone(),
            thumbs.path().to_path_buf(),
            Vec::new(),
            ThumbnailQueueHandle::default(),
            Arc::clone(&ffmpeg),
            Arc::clone(&notifier),
            vec![("vid-done".to_string(), PathBuf::from("C:/videos/done.mp4"))],
        );

        assert_eq!(extract_count_for(&ffmpeg, "vid-done"), 0);
        for i in 0..worker::THUMBNAILS_PER_VIDEO {
            let bytes = std::fs::read(dir.join(format!("vid-done_{i}.webp"))).unwrap();
            assert_eq!(bytes, b"original", "slot {i} must not be overwritten");
        }
        assert_eq!(thumbnail_ready_flag(&db, "vid-done"), 1);
        assert_eq!(notifier.0.load(Ordering::SeqCst), 0);
    }

    #[test]
    fn claim_is_exclusive_per_video_and_shared_across_clones() {
        let queue = ThumbnailQueueHandle::default();
        let clone = queue.clone();
        let guard = queue.try_claim("a").expect("first claim succeeds");
        assert!(clone.try_claim("a").is_none());
        assert!(
            clone.try_claim("b").is_some(),
            "other videos are unaffected"
        );
        drop(guard);
        assert!(clone.try_claim("a").is_some());
    }

    #[test]
    fn claim_is_released_after_normal_completion_and_after_err() {
        let queue = ThumbnailQueueHandle::default();
        let ok: Result<(), String> = {
            let _guard = queue.try_claim("v").unwrap();
            Ok(())
        };
        assert!(ok.is_ok());
        assert!(queue.try_claim("v").is_some(), "released after Ok");

        let err: Result<(), String> = (|| {
            let _guard = queue.try_claim("v").unwrap();
            Err("generation failed".to_string())?;
            Ok(())
        })();
        assert!(err.is_err());
        assert!(queue.try_claim("v").is_some(), "released after Err");
    }

    #[test]
    fn claim_is_released_after_a_panic() {
        let queue = ThumbnailQueueHandle::default();
        let worker_queue = queue.clone();
        let result = thread::spawn(move || {
            let _guard = worker_queue.try_claim("v").unwrap();
            panic!("worker blew up");
        })
        .join();
        assert!(result.is_err());
        assert!(queue.try_claim("v").is_some(), "released after panic");
    }

    #[test]
    fn orphan_tmp_files_are_removed_but_final_webp_files_are_kept() {
        let root = tempfile::tempdir().unwrap();
        let sub = root.path().join("folder-sub");
        std::fs::create_dir_all(sub.join("deeper")).unwrap();
        let tmp_names = [
            "id_0.webp.tmp",
            "id_1.webp.123-4.tmp",
            "id.wb_legacy.webp.tmp",
        ];
        let keep_names = ["id_0.webp", "id_1.webp", "notes.txt"];
        for dir in [root.path(), sub.as_path()] {
            for n in tmp_names.iter().chain(keep_names.iter()) {
                std::fs::write(dir.join(n), b"x").unwrap();
            }
        }
        // Two levels down is out of scope and must be left alone.
        std::fs::write(sub.join("deeper").join("id_9.webp.tmp"), b"x").unwrap();

        let removed = remove_orphan_tmp_files(root.path());

        assert_eq!(removed, tmp_names.len() * 2);
        for dir in [root.path(), sub.as_path()] {
            for n in tmp_names {
                assert!(!dir.join(n).exists(), "{n} should be removed");
            }
            for n in keep_names {
                assert!(dir.join(n).exists(), "{n} must be kept");
            }
        }
        assert!(sub.join("deeper").join("id_9.webp.tmp").exists());
        assert_eq!(remove_orphan_tmp_files(&root.path().join("missing")), 0);
    }

    #[test]
    fn a_stalled_video_is_recovered_by_cleanup_then_requeue() {
        let (_db_dir, db) = init_temp_db();
        let thumbs = tempfile::tempdir().unwrap();
        let dir = unassigned_dir(thumbs.path());
        insert_test_video(&db, "vid-stuck", "C:/videos/stuck.mp4");
        // Stalled state: some slots published, tmp files stranded, no
        // attempt recorded.
        std::fs::create_dir_all(&dir).unwrap();
        for i in 0..3 {
            std::fs::write(dir.join(format!("vid-stuck_{i}.webp")), b"old").unwrap();
        }
        std::fs::write(dir.join("vid-stuck_3.webp.tmp"), b"old").unwrap();
        std::fs::write(dir.join("vid-stuck_4.webp.99-1.tmp"), b"old").unwrap();
        assert_eq!(thumbnail_ready_flag(&db, "vid-stuck"), 0);

        assert_eq!(remove_orphan_tmp_files(thumbs.path()), 2);
        let pending = worker::list_videos_missing_thumbnails(&db, thumbs.path(), &[]).unwrap();
        assert_eq!(pending.len(), 1);
        assert_eq!(pending[0].0, "vid-stuck");

        let ffmpeg = available_ffmpeg(Duration::ZERO);
        run_thumbnail_queue(
            db.clone(),
            thumbs.path().to_path_buf(),
            ThumbnailQueueHandle::default(),
            Arc::clone(&ffmpeg),
            Arc::new(CountingNotifier(AtomicUsize::new(0))),
        );

        assert!(six_finals_exist(&dir, "vid-stuck"));
        assert_eq!(thumbnail_ready_flag(&db, "vid-stuck"), 1);
        assert!(std::fs::read_dir(&dir)
            .unwrap()
            .flatten()
            .all(|e| !e.file_name().to_string_lossy().ends_with(".tmp")));
    }
}
